DROP POLICY IF EXISTS "Authenticated users can view profiles"
    ON public.profiles;
CREATE POLICY "Authenticated users can view profiles"
    ON public.profiles FOR SELECT TO authenticated USING (id = auth.uid());
DROP POLICY IF EXISTS "Users can create their own profile"
    ON public.profiles;
CREATE POLICY "Users can create their own profile"
    ON public.profiles FOR INSERT TO authenticated
    WITH CHECK (id = auth.uid());
DROP POLICY IF EXISTS "Users can update their own profile"
    ON public.profiles;
CREATE POLICY "Users can update their own profile"
    ON public.profiles FOR UPDATE TO authenticated USING (id = auth.uid())
    WITH CHECK (id = auth.uid());
REVOKE UPDATE ON public.profiles FROM authenticated;
GRANT UPDATE (nombre, descripcion, habilidades)
    ON public.profiles TO authenticated;

DROP POLICY IF EXISTS "Authenticated users can view projects"
    ON public.projects;
CREATE POLICY "Authenticated users can view projects"
    ON public.projects FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "Users can create their own projects"
    ON public.projects;
CREATE POLICY "Users can create their own projects"
    ON public.projects FOR INSERT TO authenticated
    WITH CHECK (owner_id = auth.uid());
DROP POLICY IF EXISTS "Owners can update their projects"
    ON public.projects;
CREATE POLICY "Owners can update their projects"
    ON public.projects FOR UPDATE TO authenticated USING (owner_id = auth.uid())
    WITH CHECK (owner_id = auth.uid());

DROP POLICY IF EXISTS "Authenticated users can view tasks"
    ON public.tasks;
CREATE POLICY "Authenticated users can view tasks"
    ON public.tasks FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "Project owners can manage tasks"
    ON public.tasks;
CREATE POLICY "Project owners can manage tasks"
    ON public.tasks FOR ALL TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.projects
             WHERE projects.id = tasks.project_id
               AND projects.owner_id = auth.uid()
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.projects
             WHERE projects.id = tasks.project_id
               AND projects.owner_id = auth.uid()
        )
    );

DROP POLICY IF EXISTS "Contributors and project owners can view contributions"
    ON public.contributions;
CREATE POLICY "Contributors and project owners can view contributions"
    ON public.contributions FOR SELECT TO authenticated
    USING (
        usuario_id = auth.uid()
        OR EXISTS (
            SELECT 1
              FROM public.tasks
              JOIN public.projects ON projects.id = tasks.project_id
             WHERE tasks.id = contributions.task_id
               AND projects.owner_id = auth.uid()
        )
    );

