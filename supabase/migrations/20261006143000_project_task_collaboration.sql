CREATE TABLE IF NOT EXISTS public.profiles (
    id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email text NOT NULL DEFAULT '',
    nombre text NOT NULL DEFAULT '',
    habilidades jsonb NOT NULL DEFAULT '{}'::jsonb,
    reputacion integer NOT NULL DEFAULT 0,
    tareas_completadas integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo text NOT NULL,
    descripcion text NOT NULL DEFAULT '',
    owner_id uuid REFERENCES auth.users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
    titulo text NOT NULL,
    habilidades_requeridas jsonb NOT NULL DEFAULT '[]'::jsonb,
    instrucciones text NOT NULL DEFAULT '',
    restricciones text NOT NULL DEFAULT '',
    recursos text NOT NULL DEFAULT '',
    objetivo text NOT NULL DEFAULT '',
    entregables text NOT NULL DEFAULT '',
    criterios_aceptacion text NOT NULL DEFAULT '',
    estado text NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'en_progreso', 'en_revision', 'completada')),
    asignado_a uuid REFERENCES auth.users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.contributions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
    usuario_id uuid NOT NULL REFERENCES auth.users(id),
    github_pr_url text NOT NULL,
    estado text NOT NULL DEFAULT 'pendiente_revision'
        CHECK (estado IN ('pendiente_revision', 'aceptada', 'rechazada')),
    puntuacion integer NOT NULL DEFAULT 5 CHECK (puntuacion >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.profiles
    ADD COLUMN IF NOT EXISTS descripcion text NOT NULL DEFAULT '';

ALTER TABLE public.projects
    ADD COLUMN IF NOT EXISTS owner_id uuid REFERENCES auth.users(id);

ALTER TABLE public.tasks
    ADD COLUMN IF NOT EXISTS recursos text NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS criterios_aceptacion text NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS modo_entrega text NOT NULL DEFAULT 'Pull Request de GitHub',
    ADD COLUMN IF NOT EXISTS duracion_estimada_horas integer NOT NULL DEFAULT 4
        CHECK (duracion_estimada_horas BETWEEN 1 AND 8),
    ADD COLUMN IF NOT EXISTS dificultad text NOT NULL DEFAULT 'Media'
        CHECK (dificultad IN ('Baja', 'Media', 'Alta'));

ALTER TABLE public.contributions
    ADD COLUMN IF NOT EXISTS github_owner text,
    ADD COLUMN IF NOT EXISTS github_repo text,
    ADD COLUMN IF NOT EXISTS github_pr_number integer,
    ADD COLUMN IF NOT EXISTS reputacion_otorgada boolean NOT NULL DEFAULT false;

CREATE UNIQUE INDEX IF NOT EXISTS contributions_github_pr_unique
    ON public.contributions (github_owner, github_repo, github_pr_number)
    WHERE github_owner IS NOT NULL
      AND github_repo IS NOT NULL
      AND github_pr_number IS NOT NULL;

CREATE OR REPLACE FUNCTION public.create_profile_for_auth_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_profile public.profiles%ROWTYPE;
BEGIN
    v_profile := jsonb_populate_record(
        NULL::public.profiles,
        jsonb_build_object(
            'id', NEW.id,
            'email', coalesce(
                NEW.email,
                NEW.raw_user_meta_data->>'email',
                ''
            ),
            'nombre', coalesce(NEW.raw_user_meta_data->>'nombre', ''),
            'descripcion', '',
            'habilidades', '{}'::jsonb,
            'reputacion', 0,
            'tareas_completadas', 0
        )
    );
    INSERT INTO public.profiles (
        id, email, nombre, descripcion, habilidades, reputacion,
        tareas_completadas
    )
    VALUES (
        v_profile.id, v_profile.email, v_profile.nombre, v_profile.descripcion,
        v_profile.habilidades, v_profile.reputacion, v_profile.tareas_completadas
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created_profile ON auth.users;
CREATE TRIGGER on_auth_user_created_profile
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.create_profile_for_auth_user();

INSERT INTO public.profiles (
    id, email, nombre, descripcion, habilidades, reputacion, tareas_completadas
)
SELECT profile.id, profile.email, profile.nombre, profile.descripcion,
       profile.habilidades, profile.reputacion, profile.tareas_completadas
  FROM auth.users AS auth_user
 CROSS JOIN LATERAL jsonb_populate_record(
     NULL::public.profiles,
     jsonb_build_object(
         'id', auth_user.id,
         'email', coalesce(
             auth_user.email,
             auth_user.raw_user_meta_data->>'email',
             ''
         ),
         'nombre', coalesce(auth_user.raw_user_meta_data->>'nombre', ''),
         'descripcion', '',
         'habilidades', '{}'::jsonb,
         'reputacion', 0,
         'tareas_completadas', 0
     )
 ) AS profile
ON CONFLICT (id) DO NOTHING;

CREATE OR REPLACE FUNCTION public.jsonb_text_values(p_value jsonb)
RETURNS SETOF text
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT jsonb_array_elements_text(
        CASE WHEN jsonb_typeof(p_value) = 'array'
             THEN p_value ELSE '[]'::jsonb END
    )
    UNION ALL
    SELECT jsonb_object_keys(
        CASE WHEN jsonb_typeof(p_value) = 'object'
             THEN p_value ELSE '{}'::jsonb END
    )
$$;

CREATE OR REPLACE FUNCTION public.create_project_with_tasks(
    p_titulo text,
    p_descripcion text,
    p_tasks jsonb
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_project_id public.projects.id%TYPE;
    v_item jsonb;
    v_task public.tasks%ROWTYPE;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para crear un proyecto';
    END IF;
    IF length(trim(coalesce(p_titulo, ''))) = 0 THEN
        RAISE EXCEPTION 'El título del proyecto es obligatorio';
    END IF;
    IF jsonb_typeof(p_tasks) <> 'array' OR jsonb_array_length(p_tasks) = 0 THEN
        RAISE EXCEPTION 'El proyecto debe contener al menos una tarea';
    END IF;

    INSERT INTO public.projects (titulo, descripcion, owner_id)
    VALUES (trim(p_titulo), coalesce(p_descripcion, ''), auth.uid())
    RETURNING id INTO v_project_id;

    FOR v_item IN SELECT value FROM jsonb_array_elements(p_tasks)
    LOOP
        IF length(trim(coalesce(v_item->>'titulo', ''))) = 0 THEN
            RAISE EXCEPTION 'Todas las tareas deben tener un título';
        END IF;
        IF length(trim(coalesce(v_item->>'instrucciones', ''))) = 0
           OR length(trim(coalesce(v_item->>'objetivo', ''))) = 0
           OR length(trim(coalesce(v_item->>'recursos', ''))) = 0
           OR length(trim(coalesce(v_item->>'criterios_aceptacion', ''))) = 0
           OR length(trim(coalesce(v_item->>'modo_entrega', ''))) = 0 THEN
            RAISE EXCEPTION 'Todas las tareas deben incluir instrucciones, objetivo, recursos, criterios de aceptación y modo de entrega';
        END IF;
        IF CASE
            WHEN jsonb_typeof(v_item->'habilidades_requeridas') = 'array'
            THEN jsonb_array_length(v_item->'habilidades_requeridas') > 0
            ELSE false
        END IS NOT TRUE THEN
            RAISE EXCEPTION 'Todas las tareas deben requerir al menos una habilidad';
        END IF;
        IF coalesce(
            (v_item->>'duracion_estimada_horas') ~ '^[1-8]$',
            false
        ) IS NOT TRUE THEN
            RAISE EXCEPTION 'La duración de cada tarea debe ser de 1 a 8 horas';
        END IF;
        IF coalesce(v_item->>'dificultad', '') NOT IN ('Baja', 'Media', 'Alta') THEN
            RAISE EXCEPTION 'La dificultad debe ser Baja, Media o Alta';
        END IF;

        v_task := jsonb_populate_record(
            NULL::public.tasks,
            jsonb_build_object(
                'project_id', v_project_id,
                'titulo', trim(v_item->>'titulo'),
                'habilidades_requeridas',
                    coalesce(v_item->'habilidades_requeridas', '[]'::jsonb),
                'instrucciones', coalesce(v_item->>'instrucciones', ''),
                'objetivo', coalesce(v_item->>'objetivo', ''),
                'restricciones', '',
                'entregables', '',
                'recursos', coalesce(v_item->>'recursos', ''),
                'criterios_aceptacion',
                    coalesce(v_item->>'criterios_aceptacion', ''),
                'modo_entrega',
                    coalesce(v_item->>'modo_entrega', 'Pull Request de GitHub'),
                'duracion_estimada_horas',
                    coalesce(v_item->'duracion_estimada_horas', '4'::jsonb),
                'dificultad', coalesce(v_item->>'dificultad', 'Media'),
                'estado', 'pendiente',
                'asignado_a', NULL
            )
        );

        INSERT INTO public.tasks (
            project_id,
            titulo,
            habilidades_requeridas,
            instrucciones,
            objetivo,
            restricciones,
            entregables,
            recursos,
            criterios_aceptacion,
            modo_entrega,
            duracion_estimada_horas,
            dificultad,
            estado,
            asignado_a
        )
        VALUES (
            v_task.project_id,
            v_task.titulo,
            v_task.habilidades_requeridas,
            v_task.instrucciones,
            v_task.objetivo,
            v_task.restricciones,
            v_task.entregables,
            v_task.recursos,
            v_task.criterios_aceptacion,
            v_task.modo_entrega,
            v_task.duracion_estimada_horas,
            v_task.dificultad,
            v_task.estado,
            v_task.asignado_a
        );
    END LOOP;

    RETURN v_project_id::text;
END;
$$;

CREATE OR REPLACE FUNCTION public.find_compatible_tasks()
RETURNS SETOF public.tasks
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT task.*
      FROM public.tasks AS task
     WHERE auth.uid() IS NOT NULL
       AND task.estado = 'pendiente'
       AND EXISTS (
           SELECT 1
             FROM public.profiles AS profile
            WHERE profile.id = auth.uid()
              AND EXISTS (
                  SELECT 1
                    FROM public.jsonb_text_values(
                        to_jsonb(task.habilidades_requeridas)
                    ) AS required(skill)
                    JOIN public.jsonb_text_values(
                        to_jsonb(profile.habilidades)
                    ) AS owned(skill)
                      ON lower(trim(required.skill)) = lower(trim(owned.skill))
              )
       )
$$;

CREATE OR REPLACE FUNCTION public.claim_task(p_task_id text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id uuid := auth.uid();
    v_claimed_id text;
BEGIN
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para aceptar una tarea';
    END IF;

    UPDATE public.tasks AS task
       SET estado = 'en_progreso', asignado_a = v_user_id
     WHERE task.id::text = p_task_id
       AND task.estado = 'pendiente'
       AND EXISTS (
           SELECT 1
             FROM public.profiles AS profile
            WHERE profile.id = v_user_id
              AND EXISTS (
                  SELECT 1
                    FROM public.jsonb_text_values(
                        to_jsonb(task.habilidades_requeridas)
                    ) AS required(skill)
                    JOIN public.jsonb_text_values(
                        to_jsonb(profile.habilidades)
                    ) AS owned(skill)
                      ON lower(trim(required.skill)) = lower(trim(owned.skill))
              )
       )
    RETURNING task.id::text INTO v_claimed_id;

    IF v_claimed_id IS NULL THEN
        RAISE EXCEPTION 'La tarea ya no está disponible o tus habilidades no coinciden';
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_task_pr(
    p_task_id text,
    p_pr_url text,
    p_github_owner text,
    p_github_repo text,
    p_github_pr_number integer
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id uuid := auth.uid();
    v_task public.tasks%ROWTYPE;
BEGIN
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para entregar una tarea';
    END IF;

    SELECT * INTO v_task
      FROM public.tasks
     WHERE id::text = p_task_id
       AND asignado_a = v_user_id
       AND estado = 'en_progreso'
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'La tarea no está asignada a tu usuario o no está en progreso';
    END IF;

    INSERT INTO public.contributions (
        task_id, usuario_id, github_pr_url, github_owner, github_repo,
        github_pr_number, estado, puntuacion
    )
    VALUES (
        v_task.id, v_user_id, p_pr_url, p_github_owner, p_github_repo,
        p_github_pr_number, 'pendiente_revision', 5
    );

    UPDATE public.tasks SET estado = 'en_revision' WHERE id = v_task.id;
END;
$$;

CREATE OR REPLACE FUNCTION public.complete_merged_pr(
    p_github_owner text,
    p_github_repo text,
    p_github_pr_number integer,
    p_merged boolean
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_contribution public.contributions%ROWTYPE;
    v_task public.tasks%ROWTYPE;
    v_result text := 'not_found';
BEGIN
    SELECT * INTO v_contribution
      FROM public.contributions
     WHERE lower(github_owner) = lower(p_github_owner)
       AND lower(github_repo) = lower(p_github_repo)
       AND github_pr_number = p_github_pr_number
     FOR UPDATE;

    IF NOT FOUND THEN
        RETURN v_result;
    END IF;

    SELECT * INTO v_task
      FROM public.tasks
     WHERE id = v_contribution.task_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No se encontró la tarea asociada a la contribución';
    END IF;

    IF p_merged THEN
        IF NOT v_contribution.reputacion_otorgada THEN
            UPDATE public.profiles
               SET reputacion = coalesce(reputacion, 0)
                                 + (coalesce(v_contribution.puntuacion, 5) * 100),
                   tareas_completadas = coalesce(tareas_completadas, 0) + 1
             WHERE id = v_contribution.usuario_id;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'No se encontró el perfil del colaborador';
            END IF;
            UPDATE public.contributions
               SET estado = 'aceptada', reputacion_otorgada = true
             WHERE id = v_contribution.id;
            UPDATE public.tasks SET estado = 'completada' WHERE id = v_task.id;
            v_result := 'completed';
        ELSE
            v_result := 'already_completed';
        END IF;
    ELSE
        UPDATE public.contributions SET estado = 'rechazada'
         WHERE id = v_contribution.id AND NOT reputacion_otorgada;
        UPDATE public.tasks
           SET estado = 'pendiente', asignado_a = NULL
         WHERE id = v_task.id AND estado = 'en_revision';
        v_result := 'rejected';
    END IF;

    RETURN v_result;
END;
$$;

