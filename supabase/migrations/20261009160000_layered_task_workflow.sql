CREATE OR REPLACE FUNCTION public.find_compatible_modules()
RETURNS SETOF public.project_modules
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT module.*
      FROM public.project_modules module
      JOIN public.profiles profile ON profile.id = auth.uid()
      JOIN public.projects project ON project.id::text = module.project_id
     WHERE auth.uid() IS NOT NULL
       AND module.estado = 'pendiente'
       AND project.owner_id IS DISTINCT FROM auth.uid()
       AND NOT EXISTS (
           SELECT 1 FROM public.project_module_assignments history
            WHERE history.module_id = module.id
              AND history.collaborator_id = auth.uid()
       )
       AND EXISTS (
           SELECT 1
             FROM public.jsonb_text_values(module.habilidades_requeridas) required(skill)
             JOIN public.jsonb_text_values(to_jsonb(profile.habilidades)) owned(skill)
               ON lower(trim(required.skill)) = lower(trim(owned.skill))
       )
     ORDER BY (
         SELECT count(DISTINCT lower(trim(required.skill)))
           FROM public.jsonb_text_values(module.habilidades_requeridas) required(skill)
           JOIN public.jsonb_text_values(to_jsonb(profile.habilidades)) owned(skill)
             ON lower(trim(required.skill)) = lower(trim(owned.skill))
     ) DESC, module.id
$$;

CREATE OR REPLACE FUNCTION public.claim_project_module(p_module_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id uuid := auth.uid();
    v_module public.project_modules%ROWTYPE;
BEGIN
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para colaborar en un módulo';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended(v_user_id::text, 0));
    IF EXISTS (
        SELECT 1 FROM public.project_modules
         WHERE asignado_a = v_user_id AND estado = 'en_progreso'
    ) OR EXISTS (
        SELECT 1 FROM public.tasks
         WHERE asignado_a = v_user_id AND estado = 'en_progreso'
    ) THEN
        RAISE EXCEPTION 'Termina tu asignación en progreso antes de aceptar otra';
    END IF;
    SELECT module.* INTO v_module
      FROM public.project_modules module
      JOIN public.profiles profile ON profile.id = v_user_id
      JOIN public.projects project ON project.id::text = module.project_id
     WHERE module.id = p_module_id
       AND module.estado = 'pendiente'
       AND project.owner_id IS DISTINCT FROM v_user_id
       AND NOT EXISTS (
           SELECT 1 FROM public.project_module_assignments history
            WHERE history.module_id = module.id
              AND history.collaborator_id = v_user_id
       )
       AND EXISTS (
           SELECT 1
             FROM public.jsonb_text_values(module.habilidades_requeridas) required(skill)
             JOIN public.jsonb_text_values(to_jsonb(profile.habilidades)) owned(skill)
               ON lower(trim(required.skill)) = lower(trim(owned.skill))
       )
     FOR UPDATE OF module;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El módulo ya no está disponible o tus habilidades no coinciden';
    END IF;
    UPDATE public.project_modules
       SET estado = 'en_progreso',
           asignado_a = v_user_id,
           deadline_at = now() + make_interval(hours => v_module.claim_timeout_hours)
     WHERE id = v_module.id;
    INSERT INTO public.project_module_assignments (module_id, collaborator_id)
    VALUES (v_module.id, v_user_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_module_task_proposal(
    p_module_id bigint,
    p_tasks jsonb
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id uuid := auth.uid();
    v_module public.project_modules%ROWTYPE;
    v_proposal_id bigint;
    v_task jsonb;
BEGIN
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para proponer tareas';
    END IF;
    IF jsonb_typeof(p_tasks) IS DISTINCT FROM 'array' THEN
        RAISE EXCEPTION 'Las tareas propuestas deben ser una lista';
    END IF;
    IF jsonb_array_length(p_tasks) = 0 THEN
        RAISE EXCEPTION 'Propón al menos una tarea';
    END IF;
    SELECT * INTO v_module
      FROM public.project_modules
     WHERE id = p_module_id
       AND asignado_a = v_user_id
       AND estado = 'en_progreso'
       AND deadline_at > now()
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El módulo no está asignado a tu usuario o venció';
    END IF;
    FOR v_task IN SELECT value FROM jsonb_array_elements(p_tasks)
    LOOP
        IF length(trim(coalesce(v_task->>'titulo', ''))) = 0
           OR length(trim(coalesce(v_task->>'instrucciones', ''))) = 0
           OR length(trim(coalesce(v_task->>'objetivo', ''))) = 0
           OR length(trim(coalesce(v_task->>'restricciones', ''))) = 0
           OR length(trim(coalesce(v_task->>'entregables', ''))) = 0
           OR length(trim(coalesce(v_task->>'recursos', ''))) = 0
           OR length(trim(coalesce(v_task->>'criterios_aceptacion', ''))) = 0
           OR length(trim(coalesce(v_task->>'modo_entrega', ''))) = 0
           OR coalesce(v_task->>'repositorio_url', '')
              !~ '^https://github\.com/[^/]+/[^/?#]+(/|$)'
           OR coalesce(v_task->>'duracion_estimada_horas', '') !~ '^[1-8]$'
           OR coalesce(v_task->>'dificultad', '') NOT IN ('Baja', 'Media', 'Alta') THEN
            RAISE EXCEPTION 'Completa todos los campos válidos de cada tarea propuesta';
        END IF;
        IF jsonb_typeof(v_task->'habilidades_requeridas') IS DISTINCT FROM 'array' THEN
            RAISE EXCEPTION 'Cada tarea requiere habilidades en formato de lista';
        END IF;
        IF jsonb_array_length(v_task->'habilidades_requeridas') = 0 THEN
            RAISE EXCEPTION 'Cada tarea requiere al menos una habilidad';
        END IF;
        IF coalesce(v_task->>'review_mode', v_module.review_mode)
           NOT IN ('direct', 'layered') THEN
            RAISE EXCEPTION 'El flujo de revisión de cada tarea no es válido';
        END IF;
        IF lower(trim(v_task->>'repositorio_url'))
           <> lower(trim(v_module.repositorio_url)) THEN
            RAISE EXCEPTION 'Las tareas deben usar el repositorio definido por el creador';
        END IF;
    END LOOP;

    INSERT INTO public.module_task_proposals (module_id, proposer_id, tasks)
    VALUES (p_module_id, v_user_id, p_tasks)
    RETURNING id INTO v_proposal_id;
    UPDATE public.project_modules
       SET estado = 'en_revision',
           deadline_at = now() + make_interval(
               hours => creator_review_timeout_hours
           )
     WHERE id = p_module_id;
    RETURN v_proposal_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.decide_module_task_proposal(
    p_proposal_id bigint,
    p_decision text,
    p_feedback text DEFAULT ''
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_proposal public.module_task_proposals%ROWTYPE;
    v_module public.project_modules%ROWTYPE;
    v_project public.projects%ROWTYPE;
    v_task jsonb;
    v_item public.tasks%ROWTYPE;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión';
    END IF;
    IF p_decision IS DISTINCT FROM 'accepted'
       AND p_decision IS DISTINCT FROM 'changes_requested' THEN
        RAISE EXCEPTION 'La decisión sobre la propuesta no es válida';
    END IF;
    IF p_decision = 'changes_requested' AND length(trim(coalesce(p_feedback, ''))) = 0 THEN
        RAISE EXCEPTION 'Explica qué debe cambiar en la propuesta';
    END IF;
    SELECT * INTO v_proposal
      FROM public.module_task_proposals
     WHERE id = p_proposal_id AND estado = 'pendiente_revision'
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La propuesta ya no está pendiente de revisión';
    END IF;
    SELECT * INTO v_module
      FROM public.project_modules
     WHERE id = v_proposal.module_id
     FOR UPDATE;
    IF v_module.estado <> 'en_revision'
       OR v_module.deadline_at IS NULL
       OR v_module.deadline_at <= now() THEN
        RAISE EXCEPTION 'El plazo de revisión de esta propuesta venció';
    END IF;
    SELECT * INTO v_project
      FROM public.projects
     WHERE id::text = v_module.project_id;
    IF v_project.owner_id IS DISTINCT FROM auth.uid() THEN
        RAISE EXCEPTION 'Solo el creador del proyecto puede decidir';
    END IF;

    IF p_decision = 'changes_requested' THEN
        UPDATE public.module_task_proposals
           SET estado = 'cambios_solicitados',
               feedback = trim(p_feedback),
               decided_at = now()
         WHERE id = p_proposal_id;
        UPDATE public.project_modules
           SET estado = 'en_progreso',
               deadline_at = now() + make_interval(hours => claim_timeout_hours)
         WHERE id = v_module.id;
        RETURN 'changes_requested';
    END IF;

    FOR v_task IN SELECT value FROM jsonb_array_elements(v_proposal.tasks)
    LOOP
        v_item := jsonb_populate_record(
            NULL::public.tasks,
            jsonb_build_object(
                'project_id', v_project.id,
                'module_id', v_module.id::text,
                'titulo', trim(v_task->>'titulo'),
                'habilidades_requeridas', v_task->'habilidades_requeridas',
                'instrucciones', trim(v_task->>'instrucciones'),
                'objetivo', trim(v_task->>'objetivo'),
                'restricciones', coalesce(v_task->>'restricciones', ''),
                'entregables', coalesce(v_task->>'entregables', ''),
                'recursos', trim(v_task->>'recursos'),
                'criterios_aceptacion', trim(v_task->>'criterios_aceptacion'),
                'modo_entrega', trim(v_task->>'modo_entrega'),
                'repositorio_url', trim(v_task->>'repositorio_url'),
                'review_mode', coalesce(
                    v_task->>'review_mode', v_module.review_mode
                ),
                'duracion_estimada_horas',
                    (v_task->>'duracion_estimada_horas')::integer,
                'dificultad', v_task->>'dificultad',
                'estado', 'pendiente',
                'asignado_a', NULL,
                'claim_timeout_hours', v_module.task_claim_timeout_hours,
                'peer_review_timeout_hours', v_module.peer_review_timeout_hours,
                'creator_review_timeout_hours', v_module.creator_review_timeout_hours
            )
        );
        INSERT INTO public.tasks (
            project_id, module_id, titulo, habilidades_requeridas,
            instrucciones, objetivo, restricciones, entregables, recursos,
            criterios_aceptacion, modo_entrega, repositorio_url, review_mode,
            duracion_estimada_horas, dificultad, estado, asignado_a,
            claim_timeout_hours, peer_review_timeout_hours,
            creator_review_timeout_hours
        )
        VALUES (
            v_item.project_id, v_item.module_id, v_item.titulo,
            v_item.habilidades_requeridas, v_item.instrucciones,
            v_item.objetivo, v_item.restricciones, v_item.entregables,
            v_item.recursos, v_item.criterios_aceptacion, v_item.modo_entrega,
            v_item.repositorio_url, v_item.review_mode,
            v_item.duracion_estimada_horas,
            v_item.dificultad, v_item.estado, v_item.asignado_a,
            v_item.claim_timeout_hours, v_item.peer_review_timeout_hours,
            v_item.creator_review_timeout_hours
        );
    END LOOP;
    UPDATE public.module_task_proposals
       SET estado = 'aceptada', decided_at = now()
     WHERE id = p_proposal_id;
    UPDATE public.project_modules
       SET estado = 'completado', deadline_at = NULL
     WHERE id = v_module.id;
    RETURN 'accepted';
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_task_pr(
    p_task_id text,
    p_pr_url text,
    p_github_owner text,
    p_github_repo text,
    p_github_pr_number integer
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id uuid := auth.uid();
    v_task public.tasks%ROWTYPE;
    v_review_mode text;
    v_repo_match text[];
    v_pr_match text[];
BEGIN
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para entregar una tarea';
    END IF;
    SELECT task, task.review_mode
      INTO v_task, v_review_mode
      FROM public.tasks task
      JOIN public.projects project ON project.id = task.project_id
     WHERE task.id::text = p_task_id
       AND task.asignado_a = v_user_id
       AND task.estado = 'en_progreso'
     FOR UPDATE OF task;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La tarea no está asignada a tu usuario o no está en progreso';
    END IF;
    IF v_review_mode <> 'direct' THEN
        RAISE EXCEPTION 'Esta tarea requiere enviar el código a revisión por capas';
    END IF;
    v_pr_match := regexp_match(
        coalesce(p_pr_url, ''),
        '^https://github\.com/([^/]+)/([^/]+)/pull/([0-9]+)(/|$|\?)'
    );
    IF coalesce(p_github_owner, '') = ''
       OR coalesce(p_github_repo, '') = ''
       OR p_github_pr_number <= 0 OR v_pr_match IS NULL
       OR lower(v_pr_match[1]) <> lower(p_github_owner)
       OR lower(regexp_replace(v_pr_match[2], '\.git$', '')) <> lower(p_github_repo)
       OR v_pr_match[3]::integer <> p_github_pr_number THEN
        RAISE EXCEPTION 'La Pull Request de GitHub no es válida';
    END IF;
    IF v_task.repositorio_url <> '' THEN
        v_repo_match := regexp_match(
            v_task.repositorio_url,
            '^https://github\.com/([^/]+)/([^/?#]+)'
        );
        IF v_repo_match IS NULL
           OR lower(v_repo_match[1]) <> lower(p_github_owner)
           OR lower(regexp_replace(v_repo_match[2], '\.git$', '')) <> lower(p_github_repo) THEN
            RAISE EXCEPTION 'La Pull Request debe pertenecer al repositorio destino de la tarea';
        END IF;
    END IF;

    INSERT INTO public.contributions (
        task_id, usuario_id, github_pr_url, github_owner, github_repo,
        github_pr_number, estado, puntuacion
    )
    VALUES (
        v_task.id, v_user_id, p_pr_url, p_github_owner, p_github_repo,
        p_github_pr_number, 'pendiente_revision', 5
    );
    UPDATE public.tasks
       SET estado = 'en_revision',
           deadline_at = now() + make_interval(
               hours => v_task.creator_review_timeout_hours
           )
     WHERE id = v_task.id;
END;
$$;

CREATE OR REPLACE FUNCTION public.find_compatible_tasks()
RETURNS SETOF public.tasks
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT task.*
      FROM public.tasks AS task
      JOIN public.projects AS project ON project.id = task.project_id
      JOIN public.profiles AS profile ON profile.id = auth.uid()
     WHERE auth.uid() IS NOT NULL
       AND task.estado = 'pendiente'
       AND project.owner_id IS DISTINCT FROM auth.uid()
       AND NOT EXISTS (
           SELECT 1 FROM public.task_assignment_history history
            WHERE history.task_id = task.id::text
              AND history.collaborator_id = auth.uid()
       )
       AND EXISTS (
           SELECT 1
             FROM public.jsonb_text_values(to_jsonb(task.habilidades_requeridas)) required(skill)
             JOIN public.jsonb_text_values(to_jsonb(profile.habilidades)) owned(skill)
               ON lower(trim(required.skill)) = lower(trim(owned.skill))
       )
     ORDER BY (
         SELECT count(DISTINCT lower(trim(required.skill)))
           FROM public.jsonb_text_values(to_jsonb(task.habilidades_requeridas)) required(skill)
           JOIN public.jsonb_text_values(to_jsonb(profile.habilidades)) owned(skill)
             ON lower(trim(required.skill)) = lower(trim(owned.skill))
     ) DESC,
     task.id
$$;

CREATE OR REPLACE FUNCTION public.claim_task(p_task_id text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id uuid := auth.uid();
    v_task public.tasks%ROWTYPE;
BEGIN
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para aceptar una tarea';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended(v_user_id::text, 0));
    IF EXISTS (
        SELECT 1 FROM public.tasks
         WHERE asignado_a = v_user_id AND estado = 'en_progreso'
    ) THEN
        RAISE EXCEPTION 'Termina o revisa tu tarea en progreso antes de aceptar otra';
    END IF;

    SELECT task.* INTO v_task
      FROM public.tasks task
      JOIN public.profiles profile ON profile.id = v_user_id
      JOIN public.projects project ON project.id = task.project_id
     WHERE task.id::text = p_task_id
       AND task.estado = 'pendiente'
       AND project.owner_id IS DISTINCT FROM v_user_id
       AND NOT EXISTS (
           SELECT 1 FROM public.task_assignment_history history
            WHERE history.task_id = task.id::text
              AND history.collaborator_id = v_user_id
       )
       AND EXISTS (
           SELECT 1
             FROM public.jsonb_text_values(to_jsonb(task.habilidades_requeridas)) required(skill)
             JOIN public.jsonb_text_values(to_jsonb(profile.habilidades)) owned(skill)
               ON lower(trim(required.skill)) = lower(trim(owned.skill))
       )
     FOR UPDATE OF task;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'La tarea ya no está disponible o tus habilidades no coinciden';
    END IF;

    UPDATE public.tasks
       SET estado = 'en_progreso',
           asignado_a = v_user_id,
           deadline_at = now() + make_interval(hours => v_task.claim_timeout_hours)
     WHERE id = v_task.id;

    INSERT INTO public.task_assignment_history (task_id, collaborator_id)
    VALUES (v_task.id::text, v_user_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.submit_layered_task_code(
    p_task_id text,
    p_code_url text
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id uuid := auth.uid();
    v_task public.tasks%ROWTYPE;
    v_contribution_id text;
    v_reviewer_ids uuid[];
BEGIN
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para entregar una tarea';
    END IF;
    IF coalesce(p_code_url, '') !~ '^https://github\.com/[^/]+/[^/]+(/|$)' THEN
        RAISE EXCEPTION 'Introduce un enlace HTTPS válido de GitHub';
    END IF;

    SELECT task.* INTO v_task
      FROM public.tasks task
      JOIN public.projects project ON project.id = task.project_id
     WHERE task.id::text = p_task_id
       AND task.asignado_a = v_user_id
       AND task.estado = 'en_progreso'
       AND task.review_mode = 'layered'
     FOR UPDATE OF task;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La tarea no está asignada a tu usuario o no usa revisión por capas';
    END IF;

    INSERT INTO public.contributions (
        task_id, usuario_id, github_pr_url, code_url, estado, puntuacion,
        workflow_state, round_number
    )
    VALUES (
        v_task.id, v_user_id, p_code_url, p_code_url, 'pendiente_revision',
        5, 'peer_review',
        coalesce((
            SELECT max(c.round_number) + 1
              FROM public.contributions c
             WHERE c.task_id::text = v_task.id::text
        ), 1)
    )
    RETURNING id::text INTO v_contribution_id;

    SELECT array_agg(candidate.id) INTO v_reviewer_ids
      FROM (
          SELECT profile.id
            FROM public.profiles profile
            JOIN public.projects project ON project.id = v_task.project_id
           WHERE profile.id <> v_user_id
             AND profile.id <> project.owner_id
           ORDER BY (
               SELECT count(DISTINCT lower(trim(required.skill)))
                 FROM public.jsonb_text_values(to_jsonb(v_task.habilidades_requeridas)) required(skill)
                 JOIN public.jsonb_text_values(to_jsonb(profile.habilidades)) owned(skill)
                   ON lower(trim(required.skill)) = lower(trim(owned.skill))
           ) DESC, random()
           LIMIT 2
      ) candidate;
    IF coalesce(array_length(v_reviewer_ids, 1), 0) <> 2 THEN
        RAISE EXCEPTION 'Se necesitan al menos dos colaboradores registrados además del autor para revisar';
    END IF;

    INSERT INTO public.task_reviews (
        task_id, contribution_id, reviewer_id, deadline_at
    )
    SELECT v_task.id::text, v_contribution_id, reviewer_id,
           now() + make_interval(hours => v_task.peer_review_timeout_hours)
      FROM unnest(v_reviewer_ids) AS reviewer_id;

    UPDATE public.tasks
       SET estado = 'en_revision', deadline_at = NULL
     WHERE id = v_task.id;
    RETURN v_contribution_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.review_layered_task(
    p_contribution_id text,
    p_decision text,
    p_feedback text DEFAULT '',
    p_revised_code_url text DEFAULT NULL
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_review public.task_reviews%ROWTYPE;
    v_contribution public.contributions%ROWTYPE;
    v_task public.tasks%ROWTYPE;
    v_accepted integer;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para revisar una tarea';
    END IF;
    IF p_decision IS DISTINCT FROM 'accepted'
       AND p_decision IS DISTINCT FROM 'changes_requested'
       AND p_decision IS DISTINCT FROM 'edited' THEN
        RAISE EXCEPTION 'La decisión de revisión no es válida';
    END IF;
    IF p_decision = 'changes_requested' AND length(trim(coalesce(p_feedback, ''))) = 0 THEN
        RAISE EXCEPTION 'Explica los cambios solicitados';
    END IF;
    IF p_decision = 'edited'
       AND coalesce(p_revised_code_url, '') !~ '^https://github\.com/[^/]+/[^/]+(/|$)' THEN
        RAISE EXCEPTION 'Incluye un enlace HTTPS de GitHub al código actualizado';
    END IF;

    SELECT * INTO v_review
      FROM public.task_reviews
     WHERE contribution_id = p_contribution_id
       AND reviewer_id = auth.uid()
       AND decision = 'pending'
     FOR UPDATE;
    IF NOT FOUND OR v_review.deadline_at <= now() THEN
        RAISE EXCEPTION 'Esta revisión ya no está asignada o ha vencido';
    END IF;

    SELECT * INTO v_contribution
      FROM public.contributions
     WHERE id::text = p_contribution_id
     FOR UPDATE;
    IF NOT FOUND OR v_contribution.workflow_state <> 'peer_review' THEN
        RAISE EXCEPTION 'La revisión de esta entrega ya no está activa';
    END IF;
    SELECT * INTO v_task
      FROM public.tasks
     WHERE id::text = v_review.task_id
     FOR UPDATE;

    UPDATE public.task_reviews
       SET decision = p_decision,
           feedback = trim(coalesce(p_feedback, '')),
           revised_code_url = p_revised_code_url,
           decided_at = now()
     WHERE id = v_review.id;

    IF p_decision = 'changes_requested' THEN
        UPDATE public.contributions
           SET workflow_state = 'changes_requested',
               estado = 'rechazada',
               creator_feedback = trim(p_feedback)
         WHERE id::text = p_contribution_id;
        UPDATE public.task_reviews
           SET decision = 'cancelled',
               feedback = 'La revisión terminó porque se solicitaron cambios.',
               decided_at = now()
         WHERE contribution_id = p_contribution_id
           AND decision = 'pending'
           AND id <> v_review.id;
        UPDATE public.tasks
           SET estado = 'en_progreso',
               deadline_at = now() + make_interval(hours => v_task.claim_timeout_hours)
         WHERE id = v_task.id;
        RETURN 'changes_requested';
    END IF;

    IF p_decision = 'edited' THEN
        UPDATE public.contributions
           SET code_url = p_revised_code_url,
               github_pr_url = p_revised_code_url
         WHERE id::text = p_contribution_id;
    END IF;

    SELECT count(*) INTO v_accepted
      FROM public.task_reviews
     WHERE contribution_id = p_contribution_id
       AND decision IN ('accepted', 'edited');
    IF v_accepted = 2 THEN
        UPDATE public.contributions
           SET workflow_state = 'awaiting_creator'
         WHERE id::text = p_contribution_id;
        UPDATE public.tasks
           SET deadline_at = now() + make_interval(hours => v_task.creator_review_timeout_hours)
         WHERE id = v_task.id;
        RETURN 'awaiting_creator';
    END IF;
    RETURN 'accepted';
END;
$$;

CREATE OR REPLACE FUNCTION public.creator_decide_layered_task(
    p_contribution_id text,
    p_decision text,
    p_feedback text DEFAULT ''
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_contribution public.contributions%ROWTYPE;
    v_task public.tasks%ROWTYPE;
    v_owner uuid;
    v_accepted integer;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión';
    END IF;
    IF p_decision IS DISTINCT FROM 'approved'
       AND p_decision IS DISTINCT FROM 'changes_requested' THEN
        RAISE EXCEPTION 'La decisión no es válida';
    END IF;
    IF p_decision = 'changes_requested' AND length(trim(coalesce(p_feedback, ''))) = 0 THEN
        RAISE EXCEPTION 'Explica por qué se rechaza la entrega';
    END IF;

    SELECT c.* INTO v_contribution
      FROM public.contributions c
     WHERE c.id::text = p_contribution_id
     FOR UPDATE;
    IF NOT FOUND
       OR v_contribution.workflow_state <> 'awaiting_creator'
       OR v_contribution.task_id IS NULL THEN
        RAISE EXCEPTION 'La entrega aún no está lista para la revisión del creador';
    END IF;
    SELECT t, p.owner_id INTO v_task, v_owner
      FROM public.tasks t
      JOIN public.projects p ON p.id = t.project_id
     WHERE t.id = v_contribution.task_id
     FOR UPDATE OF t;
    IF v_owner IS DISTINCT FROM auth.uid() THEN
        RAISE EXCEPTION 'Solo el creador del proyecto puede decidir';
    END IF;
    IF v_task.deadline_at IS NULL OR v_task.deadline_at <= now() THEN
        RAISE EXCEPTION 'El plazo para revisar esta entrega venció';
    END IF;
    SELECT count(*) INTO v_accepted
      FROM public.task_reviews
     WHERE contribution_id = p_contribution_id
       AND decision IN ('accepted', 'edited');
    IF v_accepted < 2 THEN
        RAISE EXCEPTION 'Se requieren dos revisiones aceptadas';
    END IF;

    IF p_decision = 'changes_requested' THEN
        UPDATE public.contributions
           SET workflow_state = 'changes_requested',
               estado = 'rechazada',
               creator_feedback = trim(p_feedback)
         WHERE id::text = p_contribution_id;
        UPDATE public.tasks
           SET estado = 'en_progreso',
               deadline_at = now() + make_interval(hours => v_task.claim_timeout_hours)
         WHERE id = v_task.id;
        RETURN 'changes_requested';
    END IF;

    UPDATE public.contributions
       SET workflow_state = 'awaiting_merge',
           creator_feedback = ''
     WHERE id::text = p_contribution_id;
    UPDATE public.tasks
       SET deadline_at = now() + make_interval(
           hours => v_task.creator_review_timeout_hours
       )
     WHERE id = v_task.id;
    RETURN 'awaiting_merge';
END;
$$;

