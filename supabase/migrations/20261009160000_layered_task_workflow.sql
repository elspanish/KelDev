CREATE OR REPLACE FUNCTION public.create_project_with_workflow(
    p_titulo text,
    p_descripcion text,
    p_tasks jsonb,
    p_review_mode text
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_project_id public.projects.id%TYPE;
    v_item jsonb;
    v_task public.tasks%ROWTYPE;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para crear un proyecto';
    END IF;
    IF v_task.deadline_at IS NULL OR v_task.deadline_at <= now() THEN
        RAISE EXCEPTION 'El plazo para registrar la PR final venció';
    END IF;
    IF length(trim(coalesce(p_titulo, ''))) = 0 THEN
        RAISE EXCEPTION 'El título del proyecto es obligatorio';
    END IF;
    IF p_review_mode IS DISTINCT FROM 'direct'
       AND p_review_mode IS DISTINCT FROM 'layered' THEN
        RAISE EXCEPTION 'El modo de revisión no es válido';
    END IF;
    IF jsonb_typeof(p_tasks) IS DISTINCT FROM 'array' THEN
        RAISE EXCEPTION 'El proyecto debe contener una lista de tareas';
    END IF;
    IF jsonb_array_length(p_tasks) = 0 THEN
        RAISE EXCEPTION 'El proyecto debe contener al menos una tarea';
    END IF;

    INSERT INTO public.projects (titulo, descripcion, owner_id, review_mode)
    VALUES (trim(p_titulo), coalesce(p_descripcion, ''), auth.uid(), p_review_mode)
    RETURNING id INTO v_project_id;

    FOR v_item IN SELECT value FROM jsonb_array_elements(p_tasks)
    LOOP
        IF length(trim(coalesce(v_item->>'titulo', ''))) = 0
           OR length(trim(coalesce(v_item->>'instrucciones', ''))) = 0
           OR length(trim(coalesce(v_item->>'objetivo', ''))) = 0
           OR length(trim(coalesce(v_item->>'restricciones', ''))) = 0
           OR length(trim(coalesce(v_item->>'entregables', ''))) = 0
           OR length(trim(coalesce(v_item->>'recursos', ''))) = 0
           OR length(trim(coalesce(v_item->>'criterios_aceptacion', ''))) = 0
           OR length(trim(coalesce(v_item->>'modo_entrega', ''))) = 0 THEN
            RAISE EXCEPTION 'Todas las tareas deben incluir los campos obligatorios';
        END IF;
        IF coalesce(v_item->>'repositorio_url', '')
           !~ '^https://github\.com/[^/]+/[^/?#]+(/|$)' THEN
            RAISE EXCEPTION 'Cada tarea debe indicar un repositorio destino de GitHub válido';
        END IF;
        IF jsonb_typeof(v_item->'habilidades_requeridas') IS DISTINCT FROM 'array' THEN
            RAISE EXCEPTION 'Todas las tareas deben requerir al menos una habilidad';
        END IF;
        IF jsonb_array_length(v_item->'habilidades_requeridas') = 0 THEN
            RAISE EXCEPTION 'Todas las tareas deben requerir al menos una habilidad';
        END IF;
        IF coalesce(v_item->>'duracion_estimada_horas', '') !~ '^[1-8]$'
           OR coalesce(v_item->>'dificultad', '') NOT IN ('Baja', 'Media', 'Alta') THEN
            RAISE EXCEPTION 'Duración (1-8 horas) o dificultad no válida';
        END IF;
        IF v_item->>'review_mode' IS DISTINCT FROM 'direct'
           AND v_item->>'review_mode' IS DISTINCT FROM 'layered' THEN
            RAISE EXCEPTION 'El flujo de revisión de cada tarea debe ser válido';
        END IF;
        IF coalesce(v_item->>'claim_timeout_hours', '') !~ '^[0-9]{1,3}$'
           OR coalesce(v_item->>'peer_review_timeout_hours', '') !~ '^[0-9]{1,3}$'
           OR coalesce(v_item->>'creator_review_timeout_hours', '') !~ '^[0-9]{1,3}$' THEN
            RAISE EXCEPTION 'Los límites de tiempo deben estar entre 1 y 720 horas';
        END IF;
        IF (v_item->>'claim_timeout_hours')::integer NOT BETWEEN 1 AND 720
           OR (v_item->>'peer_review_timeout_hours')::integer NOT BETWEEN 1 AND 720
           OR (v_item->>'creator_review_timeout_hours')::integer NOT BETWEEN 1 AND 720 THEN
            RAISE EXCEPTION 'Los límites de tiempo deben estar entre 1 y 720 horas';
        END IF;

        v_task := jsonb_populate_record(
            NULL::public.tasks,
            jsonb_build_object(
                'project_id', v_project_id,
                'titulo', trim(v_item->>'titulo'),
                'habilidades_requeridas', v_item->'habilidades_requeridas',
                'instrucciones', trim(v_item->>'instrucciones'),
                'objetivo', trim(v_item->>'objetivo'),
                'restricciones', coalesce(v_item->>'restricciones', ''),
                'entregables', coalesce(v_item->>'entregables', ''),
                'recursos', trim(v_item->>'recursos'),
                'criterios_aceptacion', trim(v_item->>'criterios_aceptacion'),
                'modo_entrega', trim(v_item->>'modo_entrega'),
                'repositorio_url', trim(coalesce(v_item->>'repositorio_url', '')),
                'review_mode', v_item->>'review_mode',
                'duracion_estimada_horas',
                    (v_item->>'duracion_estimada_horas')::integer,
                'dificultad', v_item->>'dificultad',
                'estado', 'pendiente',
                'asignado_a', NULL,
                'claim_timeout_hours', (v_item->>'claim_timeout_hours')::integer,
                'peer_review_timeout_hours',
                    (v_item->>'peer_review_timeout_hours')::integer,
                'creator_review_timeout_hours',
                    (v_item->>'creator_review_timeout_hours')::integer
            )
        );
        INSERT INTO public.tasks (
            project_id, titulo, habilidades_requeridas, instrucciones,
            objetivo, restricciones, entregables, recursos,
            criterios_aceptacion, modo_entrega, repositorio_url,
            review_mode, duracion_estimada_horas,
            dificultad, estado, asignado_a, claim_timeout_hours,
            peer_review_timeout_hours, creator_review_timeout_hours
        )
        VALUES (
            v_task.project_id, v_task.titulo, v_task.habilidades_requeridas,
            v_task.instrucciones, v_task.objetivo, v_task.restricciones,
            v_task.entregables, v_task.recursos, v_task.criterios_aceptacion,
            v_task.modo_entrega, v_task.repositorio_url,
            v_task.review_mode,
            v_task.duracion_estimada_horas,
            v_task.dificultad, v_task.estado, v_task.asignado_a,
            v_task.claim_timeout_hours, v_task.peer_review_timeout_hours,
            v_task.creator_review_timeout_hours
        );
    END LOOP;

    RETURN v_project_id::text;
END;
$$;

CREATE OR REPLACE FUNCTION public.create_project_with_modules(
    p_titulo text,
    p_descripcion text,
    p_modules jsonb,
    p_review_mode text
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_project_id public.projects.id%TYPE;
    v_module jsonb;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para crear un proyecto';
    END IF;
    IF length(trim(coalesce(p_titulo, ''))) = 0 THEN
        RAISE EXCEPTION 'El título del proyecto es obligatorio';
    END IF;
    IF p_review_mode IS DISTINCT FROM 'direct'
       AND p_review_mode IS DISTINCT FROM 'layered' THEN
        RAISE EXCEPTION 'El modo de revisión no es válido';
    END IF;
    IF jsonb_typeof(p_modules) IS DISTINCT FROM 'array' THEN
        RAISE EXCEPTION 'Los módulos deben ser una lista';
    END IF;
    IF jsonb_array_length(p_modules) = 0 THEN
        RAISE EXCEPTION 'Añade al menos un módulo';
    END IF;

    INSERT INTO public.projects (titulo, descripcion, owner_id, review_mode)
    VALUES (trim(p_titulo), coalesce(p_descripcion, ''), auth.uid(), p_review_mode)
    RETURNING id INTO v_project_id;

