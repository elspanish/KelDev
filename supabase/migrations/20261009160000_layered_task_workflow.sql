            trim(v_module->>'descripcion'),
            trim(v_module->>'repositorio_url'),
            v_module->'habilidades_requeridas',
            p_review_mode,
            coalesce((v_module->>'claim_timeout_hours')::integer, 72),
            coalesce((v_module->>'creator_review_timeout_hours')::integer, 72),
            coalesce((v_module->>'task_claim_timeout_hours')::integer, 72),
            coalesce((v_module->>'peer_review_timeout_hours')::integer, 48)
