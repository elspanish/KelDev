        IF length(trim(coalesce(v_module->>'titulo', ''))) = 0
           OR length(trim(coalesce(v_module->>'descripcion', ''))) = 0
           OR coalesce(v_module->>'repositorio_url', '')
              !~ '^https://github\.com/[^/]+/[^/?#]+(/|$)' THEN
            RAISE EXCEPTION 'Cada módulo debe tener título, descripción y repositorio GitHub válido';
        END IF;
        IF jsonb_typeof(v_module->'habilidades_requeridas') IS DISTINCT FROM 'array' THEN
            RAISE EXCEPTION 'Define habilidades requeridas para cada módulo';
        END IF;
        IF jsonb_array_length(v_module->'habilidades_requeridas') = 0 THEN
            RAISE EXCEPTION 'Define al menos una habilidad para cada módulo';
        END IF;
        IF coalesce(v_module->>'claim_timeout_hours', '72') !~ '^[0-9]{1,3}$'
           OR coalesce(v_module->>'creator_review_timeout_hours', '72') !~ '^[0-9]{1,3}$'
           OR coalesce(v_module->>'task_claim_timeout_hours', '72') !~ '^[0-9]{1,3}$'
           OR coalesce(v_module->>'peer_review_timeout_hours', '48') !~ '^[0-9]{1,3}$' THEN
            RAISE EXCEPTION 'Los límites de tiempo de módulos deben estar entre 1 y 720 horas';
