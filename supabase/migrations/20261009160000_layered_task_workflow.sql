    IF v_repo_match IS NULL
       OR lower(v_repo_match[1]) <> lower(p_github_owner)
       OR lower(regexp_replace(v_repo_match[2], '\.git$', '')) <> lower(p_github_repo) THEN
        RAISE EXCEPTION 'La PR final debe pertenecer al repositorio destino de la tarea';
    END IF;

    UPDATE public.contributions
       SET workflow_state = 'awaiting_merge',
           creator_feedback = '',
           github_pr_url = p_pr_url,
           github_owner = p_github_owner,
           github_repo = p_github_repo,
           github_pr_number = p_github_pr_number
     WHERE id::text = p_contribution_id;
    UPDATE public.tasks
       SET deadline_at = now() + make_interval(
           hours => v_task.creator_review_timeout_hours
       )
     WHERE id = v_task.id;
    RETURN 'awaiting_merge';
END;
$$;

CREATE OR REPLACE FUNCTION public.register_layered_final_pr(
    p_contribution_id text,
    p_pr_url text,
    p_github_owner text,
    p_github_repo text,
    p_github_pr_number integer
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_contribution public.contributions%ROWTYPE;
    v_task public.tasks%ROWTYPE;
    v_owner uuid;
    v_repo_match text[];
    v_pr_match text[];
BEGIN
    SELECT c.* INTO v_contribution
      FROM public.contributions c
      JOIN public.tasks t ON t.id = c.task_id
      JOIN public.projects p ON p.id = t.project_id
     WHERE c.id::text = p_contribution_id
     FOR UPDATE OF c;
    IF NOT FOUND OR v_contribution.workflow_state <> 'awaiting_merge' THEN
        RAISE EXCEPTION 'La entrega no está pendiente del merge final';
    END IF;
    IF v_contribution.task_id IS NULL THEN
        RAISE EXCEPTION 'La entrega no tiene una tarea asociada';
    END IF;
    SELECT owner_id INTO v_owner
      FROM public.projects p
      JOIN public.tasks t ON t.project_id = p.id
     WHERE t.id = v_contribution.task_id;
    IF v_owner IS DISTINCT FROM auth.uid() THEN
        RAISE EXCEPTION 'Solo el creador del proyecto puede registrar el merge';
    END IF;
    SELECT * INTO v_task
      FROM public.tasks
     WHERE id = v_contribution.task_id;
    IF v_task.deadline_at IS NULL OR v_task.deadline_at <= now() THEN
        RAISE EXCEPTION 'El plazo para registrar la PR final venció';
    END IF;
    IF v_task.repositorio_url <> '' THEN
        v_repo_match := regexp_match(
            v_task.repositorio_url,
            '^https://github\.com/([^/]+)/([^/?#]+)'
        );
        IF v_repo_match IS NULL
           OR lower(v_repo_match[1]) <> lower(p_github_owner)
           OR lower(regexp_replace(v_repo_match[2], '\.git$', '')) <> lower(p_github_repo) THEN
            RAISE EXCEPTION 'La PR final debe pertenecer al repositorio de destino definido en la tarea';
        END IF;
    END IF;
    v_pr_match := regexp_match(
        coalesce(p_pr_url, ''),
        '^https://github\.com/([^/]+)/([^/]+)/pull/([0-9]+)(/|$|\?)'
    );
    IF coalesce(p_github_owner, '') = ''
       OR coalesce(p_github_repo, '') = ''
       OR coalesce(p_github_pr_number, 0) <= 0
       OR v_pr_match IS NULL
       OR lower(v_pr_match[1]) <> lower(p_github_owner)
       OR lower(regexp_replace(v_pr_match[2], '\.git$', '')) <> lower(p_github_repo)
       OR v_pr_match[3]::integer <> p_github_pr_number THEN
        RAISE EXCEPTION 'La Pull Request final no es válida';
    END IF;

    UPDATE public.contributions
       SET github_pr_url = p_pr_url,
           github_owner = p_github_owner,
           github_repo = p_github_repo,
           github_pr_number = p_github_pr_number
     WHERE id::text = p_contribution_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.complete_merged_pr(
    p_github_owner text,
    p_github_repo text,
    p_github_pr_number integer,
    p_merged boolean
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_contribution public.contributions%ROWTYPE;
    v_task public.tasks%ROWTYPE;
BEGIN
    SELECT * INTO v_contribution
      FROM public.contributions
     WHERE lower(github_owner) = lower(p_github_owner)
       AND lower(github_repo) = lower(p_github_repo)
       AND github_pr_number = p_github_pr_number
     FOR UPDATE;
    IF NOT FOUND THEN
        RETURN 'not_found';
    END IF;
    SELECT * INTO v_task
      FROM public.tasks
     WHERE id = v_contribution.task_id
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'No se encontró la tarea asociada a la contribución';
    END IF;

    IF p_merged THEN
        IF v_contribution.workflow_state NOT IN ('awaiting_merge', 'completed') THEN
            RETURN 'not_ready_for_merge';
        END IF;
        IF NOT v_contribution.reputacion_otorgada THEN
            UPDATE public.profiles
               SET reputacion = coalesce(reputacion, 0)
                                 + (coalesce(v_contribution.puntuacion, 5) * 100),
                   tareas_completadas = coalesce(tareas_completadas, 0) + 1
             WHERE id = v_contribution.usuario_id;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'No se encontró el perfil del colaborador';
            END IF;
            UPDATE public.contributions
               SET estado = 'aceptada', workflow_state = 'completed',
                   reputacion_otorgada = true
             WHERE id = v_contribution.id;
            UPDATE public.tasks SET estado = 'completada', deadline_at = NULL
             WHERE id = v_task.id;
            RETURN 'completed';
        END IF;
        RETURN 'already_completed';
    END IF;

    IF v_contribution.workflow_state = 'awaiting_merge' THEN
        UPDATE public.contributions
           SET estado = 'rechazada', workflow_state = 'changes_requested',
               creator_feedback = 'La Pull Request final se cerró sin merge.'
         WHERE id = v_contribution.id AND NOT reputacion_otorgada;
        UPDATE public.tasks
           SET estado = 'en_progreso',
               deadline_at = now() + make_interval(hours => v_task.claim_timeout_hours)
         WHERE id = v_task.id;
        RETURN 'rejected';
    END IF;
    UPDATE public.contributions
       SET estado = 'rechazada', workflow_state = 'rejected'
     WHERE id = v_contribution.id AND NOT reputacion_otorgada;
    UPDATE public.tasks
       SET estado = 'pendiente', asignado_a = NULL, deadline_at = NULL
     WHERE id = v_task.id AND estado = 'en_revision';
    RETURN 'rejected';
END;
$$;

CREATE OR REPLACE FUNCTION public.expire_task_workflows()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_count integer := 0;
    v_review record;
    v_new_reviewer uuid;
BEGIN
    UPDATE public.project_modules module
       SET estado = 'pendiente', asignado_a = NULL, deadline_at = NULL
     WHERE module.estado = 'en_progreso'
       AND module.deadline_at <= now();
    UPDATE public.module_task_proposals proposal
       SET estado = 'cambios_solicitados',
           feedback = 'El plazo de revisión del creador venció; el módulo vuelve a estar disponible.',
           decided_at = now()
      FROM public.project_modules module
     WHERE proposal.module_id = module.id
       AND module.estado = 'en_revision'
       AND module.deadline_at <= now()
       AND proposal.estado = 'pendiente_revision';
    UPDATE public.project_modules module
       SET estado = 'pendiente', asignado_a = NULL, deadline_at = NULL
     WHERE module.estado = 'en_revision'
       AND module.deadline_at <= now();
    UPDATE public.project_module_assignments history
       SET expired_at = now()
      FROM public.project_modules module
     WHERE history.module_id = module.id
       AND module.estado = 'pendiente'
       AND history.expired_at IS NULL;

    UPDATE public.tasks task
       SET estado = 'pendiente', asignado_a = NULL, deadline_at = NULL
     WHERE task.estado = 'en_progreso'
       AND task.deadline_at <= now();
    GET DIAGNOSTICS v_count = ROW_COUNT;
    UPDATE public.task_assignment_history history
       SET expired_at = now()
      FROM public.tasks task
     WHERE history.task_id = task.id::text
       AND task.estado = 'pendiente'
       AND history.expired_at IS NULL;

    FOR v_review IN
        SELECT review.id, review.task_id, review.contribution_id,
               review.reviewer_id, task.habilidades_requeridas,
               task.project_id, task.peer_review_timeout_hours
          FROM public.task_reviews review
          JOIN public.contributions contribution
            ON contribution.id::text = review.contribution_id
          JOIN public.tasks task ON task.id::text = review.task_id
         WHERE review.decision = 'pending'
           AND review.deadline_at <= now()
           AND contribution.workflow_state = 'peer_review'
         FOR UPDATE OF review
    LOOP
        SELECT profile.id INTO v_new_reviewer
          FROM public.profiles profile
          JOIN public.projects project ON project.id = v_review.project_id
         WHERE profile.id <> (
                   SELECT usuario_id FROM public.contributions
                    WHERE id::text = v_review.contribution_id
               )
           AND profile.id <> project.owner_id
           AND profile.id <> ALL(v_review.previous_reviewer_ids)
           AND NOT EXISTS (
               SELECT 1 FROM public.task_reviews old_review
                WHERE old_review.contribution_id = v_review.contribution_id
                  AND old_review.reviewer_id = profile.id
           )
         ORDER BY (
             SELECT count(DISTINCT lower(trim(required.skill)))
               FROM public.jsonb_text_values(to_jsonb(v_review.habilidades_requeridas)) required(skill)
               JOIN public.jsonb_text_values(to_jsonb(profile.habilidades)) owned(skill)
                 ON lower(trim(required.skill)) = lower(trim(owned.skill))
         ) DESC, random()
         LIMIT 1;
        IF v_new_reviewer IS NOT NULL THEN
            UPDATE public.task_reviews
               SET reviewer_id = v_new_reviewer,
                   previous_reviewer_ids = array_append(
                       previous_reviewer_ids, reviewer_id
                   ),
                   assigned_at = now(),
                   deadline_at = now() + make_interval(
                       hours => v_review.peer_review_timeout_hours
                   )
             WHERE id = v_review.id;
        ELSE
            UPDATE public.task_reviews
               SET deadline_at = now() + interval '1 hour'
             WHERE id = v_review.id;
        END IF;
        v_new_reviewer := NULL;
    END LOOP;

    UPDATE public.contributions contribution
       SET workflow_state = 'rejected',
           estado = 'rechazada',
           creator_feedback = 'El plazo de revisión de la PR directa venció.'
      FROM public.tasks task
      JOIN public.projects project ON project.id = task.project_id
     WHERE contribution.task_id = task.id
       AND task.review_mode = 'direct'
       AND contribution.workflow_state = 'awaiting_merge'
       AND task.estado = 'en_revision'
       AND task.deadline_at <= now();
    UPDATE public.tasks task
       SET estado = 'pendiente',
           asignado_a = NULL,
           deadline_at = NULL
      FROM public.projects project
     WHERE project.id = task.project_id
       AND task.review_mode = 'direct'
       AND task.estado = 'en_revision'
       AND task.deadline_at <= now()
       AND EXISTS (
           SELECT 1 FROM public.contributions contribution
            WHERE contribution.task_id = task.id
              AND contribution.workflow_state = 'rejected'
              AND contribution.creator_feedback LIKE 'El plazo de revisión de la PR directa%'
       );

    UPDATE public.contributions contribution
       SET workflow_state = 'changes_requested',
           estado = 'rechazada',
           creator_feedback = 'El plazo de revisión del creador venció; se devuelve al colaborador.'
      FROM public.tasks task
     WHERE contribution.task_id = task.id
       AND contribution.workflow_state = 'awaiting_creator'
       AND task.deadline_at <= now();
    UPDATE public.contributions contribution
       SET workflow_state = 'rejected',
           estado = 'rechazada',
           creator_feedback = 'El plazo para completar el merge final venció.'
      FROM public.tasks task
     WHERE contribution.task_id = task.id
       AND contribution.workflow_state = 'awaiting_merge'
       AND task.deadline_at <= now()
       AND task.estado = 'en_revision';
    UPDATE public.tasks task
       SET estado = 'pendiente',
           asignado_a = NULL,
           deadline_at = NULL
     WHERE task.estado = 'en_revision'
       AND task.deadline_at <= now()
       AND EXISTS (
           SELECT 1 FROM public.contributions contribution
            WHERE contribution.task_id = task.id
              AND contribution.workflow_state = 'rejected'
              AND contribution.creator_feedback LIKE 'El plazo para completar%'
       );
    UPDATE public.tasks task
       SET estado = 'en_progreso',
           deadline_at = now() + make_interval(hours => task.claim_timeout_hours)
     WHERE task.estado = 'en_revision'
       AND task.deadline_at <= now()
       AND EXISTS (
           SELECT 1 FROM public.contributions contribution
            WHERE contribution.task_id = task.id
              AND contribution.workflow_state = 'changes_requested'
              AND contribution.creator_feedback LIKE 'El plazo de revisión%'
       );
    RETURN v_count;
END;
$$;

