        IF coalesce((v_module->>'claim_timeout_hours')::integer, 72) NOT BETWEEN 1 AND 720
           OR coalesce((v_module->>'creator_review_timeout_hours')::integer, 72) NOT BETWEEN 1 AND 720
           OR coalesce((v_module->>'task_claim_timeout_hours')::integer, 72) NOT BETWEEN 1 AND 720
           OR coalesce((v_module->>'peer_review_timeout_hours')::integer, 48) NOT BETWEEN 1 AND 720 THEN
            RAISE EXCEPTION 'Los límites de tiempo de módulos deben estar entre 1 y 720 horas';
        END IF;
        INSERT INTO public.project_modules (
            project_id, titulo, descripcion, repositorio_url, habilidades_requeridas,
            review_mode,
            claim_timeout_hours, creator_review_timeout_hours,
            task_claim_timeout_hours, peer_review_timeout_hours
